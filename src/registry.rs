use serde::Serialize;

/// 运营商分类: 主流 DNS / 其他 DNS
#[derive(Debug, Clone, Copy, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum ProviderCategory {
    Mainstream,
    Other,
}

/// 运营商凭据字段定义（key 即传给 acme.sh 的环境变量名）
#[derive(Debug, Clone, Serialize)]
pub struct ProviderFieldDef {
    pub key: &'static str,
    pub label: &'static str,
    pub placeholder: &'static str,
    pub required: bool,
    pub secret: bool,
    pub help: &'static str,
}

/// DNS 运营商类型定义（后端为唯一事实来源，前端通过 /api/providers/schema 获取）
/// key = 权威英文名（数据库保存，用于菜单匹配）; label = 中文名（菜单展示、配置名称）
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProviderTypeDef {
    pub key: &'static str,
    pub label: &'static str,
    pub label_en: &'static str,
    pub dns_hook: &'static str,
    pub category: ProviderCategory,
    pub description: &'static str,
    pub fields: &'static [ProviderFieldDef],
    /// 任选一组全部填写即可（如 Cloudflare: Token 或 邮箱+GlobalKey）
    pub require_any: &'static [&'static [&'static str]],
    /// 无需凭据（自定义脚本 / 本地插件 / 使用本机 CLI 配置等）
    pub no_creds: bool,
    /// acme.sh wiki 文档链接
    pub doc_url: &'static str,
}

